def calculate_fare(dist):
    if dist == 0:
        return 0
    fare = round(dist * 2.53)
    return max(10, fare)

def process_route(source_file, source_page, route_name, stops, distances):
    fares_list = []
    for i in range(len(stops)):
        for j in range(i + 1, len(stops)):
            dist = abs(distances[j] - distances[i])
            fare = calculate_fare(dist)
            fares_list.append({
                "from": stops[i],
                "to": stops[j],
                "fare": fare
            })
    return {
        "source_file": source_file,
        "source_page": source_page,
        "route_name": route_name,
        "stops": stops,
        "distances_km": distances,
        "fares": fares_list
    }

