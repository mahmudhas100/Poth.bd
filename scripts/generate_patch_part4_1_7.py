MIN_FARE = 10

def round_half_up(n):
    return math.floor(n + 0.5)

def calculate_fare(dist1, dist2):
    dist = abs(dist1 - dist2)
    fare = round_half_up(dist * RATE)
    return max(MIN_FARE, fare)

